"""Build the gallery, sources, and figures from the API reference."""
from argparse import ArgumentParser
from dataclasses import dataclass
from html import escape
from pathlib import Path
import re
from textwrap import indent

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import AutoLocator, MaxNLocator

import mpl3d_vtk


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
SOURCES = ROOT / "examples/reference_sources.py"
DATA_DIR = ROOT.parent / "my-mpl-style/data"
DATA_FILES = ("cheese.npz", "peanut.npz", *(f"pfc_3d_{i}_T3000.npz" for i in range(1, 4)))
PAGES = {
    "api.md": "fig, ax, t, x, y, z",
    "function_reference.md": "fig, ax, t, coordinates, x, y, z, volume, vectors, seeds",
    "scene.md": "t, x, y, z, new_scene, sample",
}
FEATURED = ("plot_isosurface", "extract_isosurface", "plot_trisurf", "plot_mesh")
CODE_BLOCK = re.compile(r"^\x60\x60\x60python\n(.*?)^\x60\x60\x60$", re.MULTILINE | re.DOTALL)
FIGURE = re.compile(r'<img src="(gallery/reference/[^"]+\.png)" width="\d+" alt="([^"]+)">')
HEADINGS = re.compile(r"^##(#?) (.+)\n", re.MULTILINE)
SOURCE_LINK = re.compile(r"\n\n\[Source code\]\(\.\./examples/reference_sources\.py#L\d+\)\.")
STYLE = {
    "figure.figsize": (4.25, 3.15),
    "figure.constrained_layout.use": True,
    "font.size": 9,
    "axes.titlesize": 10,
    "axes.titlepad": 7,
    "xtick.labelsize": 8,
    "ytick.labelsize": 8,
}


@dataclass(frozen=True)
class Example:
    page: str
    group: str
    title: str
    image: str
    alt: str
    code: str

    @property
    def name(self):
        return Path(self.image).stem


def slug(heading):
    return re.sub(r"[^a-z0-9_ -]", "", heading.lower()).replace(" ", "-")


def read_reference():
    setups = {}
    examples = []
    for page in PAGES:
        text = (DOCS / page).read_text(encoding="utf-8")
        # The generated module imports the modules shared by all three setups.
        setups[page] = CODE_BLOCK.search(text).group(1).split("\n\n", 1)[1].strip()
        sections = list(HEADINGS.finditer(text))
        ends = [h.start() for h in sections[1:]] + [len(text)]
        for heading, end in zip(sections, ends):
            if not heading[1]:
                group = heading[2]
                continue
            section = text[heading.end():end]
            image = FIGURE.search(section)
            if image is not None:
                code = CODE_BLOCK.search(section).group(1).strip()
                examples.append(Example(page, group, heading[2].strip("\x60"), *image.groups(), code))
    if len({example.name for example in examples}) != len(examples):
        raise ValueError("Reference figure filenames must be unique.")
    return setups, examples


def build_sources(setups, examples):
    header = '''"""Runnable gallery examples generated by examples/render_reference.py."""

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import mpl3d_vtk

vtkplot = mpl3d_vtk'''
    parts = [header]
    setup_names = {page: f"_setup_{Path(page).stem}" for page in PAGES}
    for page, symbols in PAGES.items():
        parts.append(
            f"def {setup_names[page]}():\n{indent(setups[page], '    ')}\n    return {symbols}"
        )

    table = []
    for example in examples:
        needs_data = "data_dir /" in example.code
        args = "data_dir" if needs_data else ""
        setup = f"    {PAGES[example.page]} = {setup_names[example.page]}()"
        body = indent(example.code, "    ")
        parts.append(f"def {example.name}({args}):\n{setup}\n{body}\n    return fig")
        table.append(f'    "{example.name}": ({example.title!r}, {example.name}, {needs_data}),')
    parts.append("FIGURES = {\n" + "\n".join(table) + "\n}")
    parts.append('''if __name__ == "__main__":
    from render_reference import render_one

    render_one(FIGURES)''')
    source = "\n\n\n".join(parts) + "\n"
    lines = {match[1]: source.count("\n", 0, match.start()) + 1
             for match in re.finditer(r"^def ([a-z][a-z0-9_]*)\(", source, re.MULTILINE)}
    return source, lines


def write_gallery(examples, lines):
    by_name = {example.name: example for example in examples}
    groups = {"Isosurfaces and triangle meshes": [by_name[name] for name in FEATURED]}
    for example in examples:
        if example.name not in FEATURED:
            groups.setdefault(example.group, []).append(example)

    page = [
        "# Gallery", "",
        "Click a figure to open its API reference. The link below it opens the Python code that draws it.",
        "",
        "- **Plot data** · [Isosurfaces and triangle meshes](#isosurfaces-and-triangle-meshes) · [Surfaces](#surfaces-and-contours) · [Charts](#lines-points-and-charts) · [Scalar fields](#meshes-and-scalar-fields) · [Vector fields](#vector-fields-and-streamlines) · [Spatial geometry](#point-clouds-and-other-geometry)",
        "- **Manage the scene** · [Axes](#axes-controls) · [Streaming lines and lights](#streaming-lines-and-lights) · [Renderer integration](#renderer-integration)",
        "- **Work with a handle** · [Inspect geometry and data](#graphic-handles) · [Update data and colors](#update-data-and-colors) · [Style and visibility](#style-and-visibility)",
    ]
    for topic, entries in groups.items():
        featured = topic == "Isosurfaces and triangle meshes"
        columns, width = (2, 420) if featured else (3, 280)
        page.extend(["", f"## {topic}", ""])
        if featured:
            page.extend([
                "These figures use the original triangle meshes and all three PFC scalar volumes.",
                "[Get the upstream data](examples.md#upstream-data) · [Compare with mplot3d](../benchmarks/results/my_mpl_style/README.md)", "",
            ])
        page.append("<table>")
        for offset in range(0, len(entries), columns):
            page.append("  <tr>")
            for entry in entries[offset:offset+columns]:
                href = f"{entry.page}#{slug(entry.title)}"
                alt = escape(f"{entry.title}. {entry.alt}", quote=True)
                source = f"../examples/{SOURCES.name}#L{lines[entry.name]}"
                page.append(
                    f'    <td align="center" width="{100 // columns}%">'
                    f'<a href="{href}"><img src="{entry.image}" width="{width}" alt="{alt}"></a><br>'
                    f'<a href="{source}">Source code</a></td>'
                )
            page.append("  </tr>")
        page.append("</table>")
    page.extend([
        "", "## More examples", "",
        "- [Three intersecting planes](examples.md#three-intersecting-planes)",
        "- [Run the examples or regenerate these figures](examples.md#regenerate-the-reference-figures)",
    ])
    (DOCS / "plot_catalog.md").write_text("\n".join(page) + "\n", encoding="utf-8")

    def add_link(match):
        stem = Path(match[1]).stem
        return match[0] + f"\n\n[Source code](../examples/{SOURCES.name}#L{lines[stem]})."

    for name in PAGES:
        path = DOCS / name
        text = SOURCE_LINK.sub("", path.read_text(encoding="utf-8"))
        path.write_text(FIGURE.sub(add_link, text), encoding="utf-8")


def render(output, title, draw, needs_data, data_dir):
    with matplotlib.rc_context(STYLE):
        try:
            figure = draw(data_dir) if needs_data else draw()
            for ax in figure.axes:
                if isinstance(ax, mpl3d_vtk.VtkAxes):
                    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
                        if isinstance(axis.get_major_locator(), AutoLocator):
                            axis.set_major_locator(MaxNLocator(nbins=3))
            figure.suptitle(title, fontfamily="monospace", fontsize=12)
            figure.savefig(output, facecolor="white", dpi=140)
        finally:
            for number in plt.get_fignums():
                figure = plt.figure(number)
                for ax in figure.axes:
                    if isinstance(ax, mpl3d_vtk.VtkAxes):
                        ax.remove()
                plt.close(figure)


def render_one(figures):
    cli = ArgumentParser(description="Render an individual API figure.")
    cli.add_argument("name", choices=figures)
    cli.add_argument("output", nargs="?", type=Path)
    cli.add_argument("--data-dir", type=Path, default=DATA_DIR)
    args = cli.parse_args()
    title, draw, needs_data = figures[args.name]
    if needs_data and not args.data_dir.is_dir():
        cli.error(f"Use --data-dir to point to my-mpl-style/data. Directory not found: {args.data_dir}")
    output = args.output or Path(f"{args.name}.png")
    render(output, title, draw, needs_data, args.data_dir)


def main(destination, data_dir):
    missing = [name for name in DATA_FILES if not (data_dir / name).is_file()]
    if missing:
        raise SystemExit(f"Use --data-dir to point to my-mpl-style/data. Missing in {data_dir}: {', '.join(missing)}")
    setups, examples = read_reference()
    source, lines = build_sources(setups, examples)
    namespace = {"__name__": "_reference_sources"}
    exec(compile(source, str(SOURCES), "exec"), namespace)
    destination.mkdir(parents=True, exist_ok=True)
    for name, (title, draw, needs_data) in namespace["FIGURES"].items():
        render(destination / f"{name}.png", title, draw, needs_data, data_dir)
    SOURCES.write_text(source, encoding="utf-8")
    write_gallery(examples, lines)
    print(f"Rendered {len(examples)} figures to {destination}")


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=DOCS / "gallery/reference")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    args = parser.parse_args()
    main(args.output, args.data_dir)
